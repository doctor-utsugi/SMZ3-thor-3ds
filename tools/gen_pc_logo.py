#!/usr/bin/env python3
"""Packs the app logo (rounded tile, transparent corners) for the frontends.

gen_pc_logo.py <logo.png> <out.c>            C file for the PC binary (128 px)
gen_pc_logo.py <logo.png> <out.png> <size>   the tile as a PNG (Android assets)
gen_pc_logo.py <logo.png> <out.pv> <size>    the tile as a preview, u8 w, u8 h, RGBA (3DS romfs)"""
import sys
from PIL import Image, ImageDraw
src, dst = sys.argv[1], sys.argv[2]
size = int(sys.argv[3]) if len(sys.argv) > 3 else 128
im = Image.open(src).convert("RGB").crop((100, 100, 924, 924)).resize((size * 4, size * 4), Image.LANCZOS)
mask = Image.new("L", im.size, 0)
ImageDraw.Draw(mask).rounded_rectangle((0, 0, im.size[0] - 1, im.size[1] - 1), radius=int(im.size[0] * 0.13), fill=255)
im = im.resize((size, size), Image.LANCZOS).convert("RGBA")
im.putalpha(mask.resize((size, size), Image.LANCZOS))
if dst.endswith(".png"):
    im.save(dst)
elif dst.endswith(".pv"):
    open(dst, "wb").write(bytes([size, size]) + im.tobytes())
else:
    out = ["/* Generated by tools/gen_pc_logo.py. Do not edit. */", "const int PC_LOGO_SIZE = %d;" % size,
           "const unsigned char PC_LOGO_RGBA[] = {" + ",".join(str(b) for b in im.tobytes()) + "};"]
    open(dst, "w").write("\n".join(out) + "\n")
