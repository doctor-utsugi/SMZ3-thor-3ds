#!/usr/bin/env python3
"""Packs the tracker assets for the 3DS: the map's room table, region boxes and markers as C (SMZ3_MAP_DATA), the combined
map as RGB565 at three sizes, and the item icons and boss tokens as .pv files (u8 w, u8 h, RGBA).

gen_3ds_assets.py <app assets dir (smz3/)> <out C file> <romfs dir>"""
import json, os, struct, sys
from PIL import Image

src, dst, romfs = sys.argv[1], sys.argv[2], sys.argv[3]
rooms = json.load(open(os.path.join(src, "sm_rooms.json")))
regions = json.load(open(os.path.join(src, "z3_regions.json")))
markers = json.load(open(os.path.join(src, "map_markers.json")))
out = ["/* Generated by tools/gen_3ds_assets.py. Do not edit. */", "#include \"smz3_discovery.h\""]
out.append("static const SmzSmRoom ROOMS[] = {" + ",".join("{%d,%d,%d,%d,%d,%d}" % tuple(r) for r in rooms) + "};")
out.append("static const SmzZRegion REGIONS[] = {" + ",".join('{"%s",{%s}}' % (k.replace('"', '\\"'), ",".join("%sf" % repr(float(v)) for v in b)) for k, b in regions.items()) + "};")
out.append("static const SmzMarker MARKERS[] = {" + ",".join("{%d,%d,%d}" % tuple(m) for m in markers) + "};")
out.append("const SmzMapData SMZ3_MAP_DATA = {ROOMS, %d, REGIONS, %d, MARKERS, %d};" % (len(rooms), len(regions), len(markers)))
open(dst, "w").write("\n".join(out) + "\n")


def rgb565(im):
    im = im.convert("RGB")
    px = im.tobytes()
    return b"".join(struct.pack("<H", ((px[i] >> 3) << 11) | ((px[i + 1] >> 2) << 5) | (px[i + 2] >> 3)) for i in range(0, len(px), 3))


# map<n>.bin: u16 w, u16 h, RGB565 rows; level n has 1/2^(n+1) pixel per unit of the 1623 x 958 marker space
os.makedirs(os.path.join(romfs, "icons"), exist_ok=True)
full = Image.open(os.path.join(src, "map.png"))
for n in range(3):
    w, h = round(1623 / 2 ** (n + 1)), round(958 / 2 ** (n + 1))
    im = full.resize((w, h), Image.LANCZOS)
    open(os.path.join(romfs, "map%d.bin" % n), "wb").write(struct.pack("<HH", w, h) + rgb565(im))


def pv(path, out_path, crop=False):
    im = Image.open(path).convert("RGBA")
    if crop and im.getbbox():
        im = im.crop(im.getchannel("A").getbbox())
    open(out_path, "wb").write(bytes([im.width, im.height]) + im.tobytes())


for name in os.listdir(os.path.join(src, "items")):
    pv(os.path.join(src, "items", name), os.path.join(romfs, "icons", name[:-4] + ".pv"))
for name in os.listdir(os.path.join(src, "rewards")):
    pv(os.path.join(src, "rewards", name), os.path.join(romfs, "icons", name[:-4] + ".pv"), crop=True)
