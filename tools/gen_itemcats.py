#!/usr/bin/env python3
"""Item and reward categories from the Cas' tracker enums -> core/gen/smz3_itemcats.h."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
enums = root / "vendor/SMZ3Randomizer/src/TrackerCouncil.Smz3.Shared/Enums"


def categories(path, enum_name, attr, cat_enum):
    text = path.read_text(encoding="utf-8-sig")
    body = text[text.index("{", text.index("enum " + enum_name)) + 1:]
    cats = re.findall(r"^\s*(\w+)\s*(?:=\s*[^,]*)?,?\s*(?://.*)?$", re.search(r"enum %s\s*\{(.*?)\n\}" % cat_enum, (enums / (cat_enum + ".cs")).read_text(encoding="utf-8-sig"), re.S).group(1), re.M)
    cats = [c for c in cats if c]
    result = {}
    value = 0
    pending = []
    for line in body.split("\n"):
        line = line.strip()
        m = re.match(r"\[%s\((.*)\)\]" % attr, line)
        if m:
            pending = re.findall(r"%s\.(\w+)" % cat_enum, m.group(1))
            continue
        m = re.match(r"(\w+)\s*(?:=\s*(0x[0-9A-Fa-f]+|\d+))?,?$", line)
        if m and not line.startswith("["):
            if m.group(2):
                value = int(m.group(2), 0)
            result[value] = pending
            pending = []
            value += 1
        if line == "}":
            break
    return cats, result


icats, items = categories(enums / "ItemType.cs", "ItemType", "ItemCategory", "ItemCategory")
rcats, rewards = categories(enums / "RewardType.cs", "RewardType", "RewardCategory", "RewardCategory")
out = ["/* Generated by tools/gen_itemcats.py. Do not edit. */", "#ifndef SMZ3_ITEMCATS_H", "#define SMZ3_ITEMCATS_H", "#include <stdint.h>", ""]
out.append("enum {")
for i, c in enumerate(icats):
    out.append(f"    ICAT_{c} = 1u << {i},")
out.append("};")
out.append("enum {")
for i, c in enumerate(rcats):
    out.append(f"    RCAT_{c} = 1u << {i},")
out.append("};")
out.append("static const uint32_t SMZ_ITEM_CATS[256] = {")
for v in sorted(items):
    if items[v]:
        out.append(f"    [{v}] = " + " | ".join(f"ICAT_{c}" for c in items[v]) + ",")
out.append("};")
out.append("static const uint32_t SMZ_REWARD_CATS[16] = {")
for v in sorted(rewards):
    if rewards[v]:
        out.append(f"    [{v}] = " + " | ".join(f"RCAT_{c}" for c in rewards[v]) + ",")
out.append("};")
out.append("#endif")
(root / "core/gen/smz3_itemcats.h").write_text("\n".join(out) + "\n")
print(len(icats), "item categories,", sum(1 for v in items.values() if v), "items with categories")
