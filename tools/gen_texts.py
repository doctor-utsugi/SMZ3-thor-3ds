#!/usr/bin/env python3
"""Generates core/gen/smz3_texts_data.h: the string table template and the strings the text writer needs.
Input: the C# StringTable.yaml and build/textdata.json (gen-cli textdata)."""
import json, os, sys, yaml
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
YAML = root + "/vendor/SMZ3Randomizer/src/TrackerCouncil.Smz3.SeedGenerator/Text/Scripts/StringTable.yaml"
data = json.load(open(root + "/build/textdata.json"))
table = yaml.safe_load(open(YAML, encoding="utf-8-sig"))

def cstr(s):
    out = ['"']
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"' or c == "\\": out.append("\\" + c)
        elif 32 <= b < 127: out.append(c)
        else: out.append("\\%03o" % b)
    out.append('"')
    return "".join(out)

o = ["/* Generated by tools/gen_texts.py. Do not edit. */", "#ifndef SMZ3_TEXTS_DATA_H", "#define SMZ3_TEXTS_DATA_H", "#include <stdint.h>", ""]
o.append("typedef struct { int n; const char *const *v; } SmzStrList;")
o.append("typedef struct { const char *name; const char *text; const uint8_t *bytes; int nbytes; } SmzTableEntry;")
o.append("")
# string table template
for i, e in enumerate(table):
    (name, val), = e.items()
    if isinstance(val, list):
        o.append("static const uint8_t TBL_BYTES_%d[] = { %s };" % (i, ", ".join(str(int(v)) for v in val)))
o.append("static const SmzTableEntry SMZ_TABLE[] = {")
for i, e in enumerate(table):
    (name, val), = e.items()
    if isinstance(val, list):
        o.append('    { "%s", 0, TBL_BYTES_%d, %d },' % (name, i, len(val)))
    else:
        o.append('    { "%s", %s, 0, 0 },' % (name, cstr(str(val))))
o.append("};")
o.append("#define SMZ_TABLE_COUNT %d" % len(table))
o.append("")
# game lines
names = sorted(data["lines"])
o.append("enum { " + ", ".join("LINE_" + n for n in names) + ", LINE_COUNT };")
for n in names:
    vs = data["lines"][n]
    o.append("static const char *const LINES_%s[] = { %s };" % (n, ", ".join(cstr(v) for v in vs) if vs else "0"))
o.append("static const SmzStrList SMZ_LINES[LINE_COUNT] = {")
for n in names:
    o.append("    [LINE_%s] = { %d, LINES_%s }," % (n, len(data["lines"][n]), n))
o.append("};")
o.append("")
# items
o.append("typedef struct { SmzStrList articled, pedestal, name; } SmzItemText;")
for t, d in sorted(data["items"].items(), key=lambda x: int(x[0])):
    for k in ("articled", "pedestal", "name"):
        vs = d[k]
        o.append("static const char *const IT_%s_%s[] = { %s };" % (t, k, ", ".join(cstr(v) for v in vs) if vs else "0"))
o.append("static const SmzItemText SMZ_ITEM_TEXT[256] = {")
for t, d in sorted(data["items"].items(), key=lambda x: int(x[0])):
    o.append("    [%s] = { { %d, IT_%s_articled }, { %d, IT_%s_pedestal }, { %d, IT_%s_name } }," % (t, len(d["articled"]), t, len(d["pedestal"]), t, len(d["name"]), t))
o.append("};")
o.append("")
# regions
for r in data["regions"]:
    vs = r["names"]
    o.append("static const char *const RN_%d[] = { %s };" % (r["index"], ", ".join(cstr(v) for v in vs) if vs else "0"))
o.append("typedef struct { const char *name, *area; SmzStrList names; } SmzRegionText;")
o.append("static const SmzRegionText SMZ_REGION_TEXT[] = {")
for r in data["regions"]:
    o.append("    { %s, %s, { %d, RN_%d } }," % (cstr(r["name"]), cstr(r["area"]), len(r["names"]), r["index"]))
o.append("};")
# letter table, parsed from Dialog.cs
import re
dialog = open(root + "/vendor/SMZ3Randomizer/src/TrackerCouncil.Smz3.SeedGenerator/Text/Dialog.cs", encoding="utf-8-sig").read()
body = dialog[dialog.index("s_letters = new Dictionary<char, byte[]>"):]
body = body[:body.index("#endregion")]
letters = []
for m in re.finditer(r"\{ '((?:\\.|[^'\\])')\s*,\s*new byte\[\] \{([^}]*)\} \}", body):
    ch = m.group(1)[:-1]
    ch = {"\\'": "'", "\\\\": "\\"}.get(ch, ch)
    bs = [int(x.strip(), 16) for x in m.group(2).split(",")]
    letters.append((ord(ch), bs))
o.append("typedef struct { uint32_t cp; uint8_t n; uint8_t b[3]; } SmzLetter;")
o.append("static const SmzLetter SMZ_LETTERS[] = {")
for cp, bs in letters:
    o.append("    { %d, %d, { %s } }," % (cp, len(bs), ", ".join("0x%02X" % b for b in bs) + (", 0" * (3 - len(bs)))))
o.append("};")
o.append("#define SMZ_LETTER_COUNT %d" % len(letters))
o.append("#endif")
open(root + "/core/gen/smz3_texts_data.h", "w").write("\n".join(o) + "\n")
print("entries", len(table), "items", len(data["items"]), "regions", len(data["regions"]))
