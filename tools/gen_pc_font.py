#!/usr/bin/env python3
"""Renders printable ASCII of Chakra Petch Bold (SIL OFL 1.1, tools/fonts) into two alpha atlases (40 px and 100 px) with per-glyph advances,
stored as C arrays (frontends/pc/font_data.c). The renderer picks the atlas nearest to the size it draws."""
import sys
from PIL import Image, ImageDraw, ImageFont

import os
BOLD = HEAVY = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts", "ChakraPetch-Bold.ttf")
chars = [chr(c) for c in range(32, 127)]
COLS = 16
out = ["/* Generated by tools/gen_pc_font.py from Chakra Petch (SIL OFL 1.1). Do not edit. */", "#include \"pc_font.h\""]
for tag, size, path in (("", 40, BOLD), ("2", 100, HEAVY)):
    m = size // 10   # an empty margin around every glyph, so the filter never picks up a neighbour
    cw, ch = size + 2 * m, int(size * 4 / 3) + 2 * m
    rows = (len(chars) + COLS - 1) // COLS
    img = Image.new("L", (COLS * cw, rows * ch), 0)
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(path, size)
    adv = []
    for i, c in enumerate(chars):
        d.text(((i % COLS) * cw + m, (i // COLS) * ch + m + size // 12), c, font=f, fill=255)
        adv.append(round(f.getlength(c) * 1000 / size))
    data = img.tobytes()
    out.append(f"const int PC_FONT{tag}_W = {img.width}, PC_FONT{tag}_H = {img.height}, PC_FONT{tag}_CW = {cw}, PC_FONT{tag}_CH = {ch}, PC_FONT{tag}_COLS = {COLS}, PC_FONT{tag}_SIZE = {size};")
    out.append(f"const short PC_FONT{tag}_ADV[] = {{{','.join(map(str, adv))}}};   /* thousandths of the size */")
    out.append(f"const unsigned char PC_FONT{tag}_ALPHA[] = {{")
    for i in range(0, len(data), 32):
        out.append(",".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "frontends/pc/font_data.c", "w").write("\n".join(out) + "\n")
