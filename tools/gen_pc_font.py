#!/usr/bin/env python3
"""Renders printable ASCII of DejaVu Sans Mono into an alpha atlas stored as a C array (frontends/pc/font_data.c)."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZE, CW, CH, COLS = 24, 15, 36, 16
chars = [chr(c) for c in range(32, 127)]
rows = (len(chars) + COLS - 1) // COLS
img = Image.new("L", (COLS * CW, rows * CH), 0)
d = ImageDraw.Draw(img)
f = ImageFont.truetype(FONT, SIZE)
for i, ch in enumerate(chars):
    d.text(((i % COLS) * CW, (i // COLS) * CH + 2), ch, font=f, fill=255)
data = img.tobytes()
out = ["/* Generated by tools/gen_pc_font.py from DejaVu Sans Mono (Bitstream Vera licence). Do not edit. */",
       "#include \"pc_font.h\"", f"const int PC_FONT_W = {img.width}, PC_FONT_H = {img.height}, PC_FONT_CW = {CW}, PC_FONT_CH = {CH}, PC_FONT_COLS = {COLS};",
       "const unsigned char PC_FONT_ALPHA[] = {"]
for i in range(0, len(data), 24):
    out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
out.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "frontends/pc/font_data.c", "w").write("\n".join(out) + "\n")
