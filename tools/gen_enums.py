#!/usr/bin/env python3
"""Turns the Cas' tracker enums (ItemType, RewardType, BossType, LocationId) into core/gen/smz3_enums.h."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
enums = root / "vendor/SMZ3Randomizer/src/TrackerCouncil.Smz3.Shared/Enums"


def parse(path, name):
    text = path.read_text(encoding="utf-8-sig")
    body = text[text.index("{", text.index("enum " + name)) + 1:]
    body = body[:body.index("\n}")]
    body = re.sub(r"\[[^\]]*\]", "", body)
    body = re.sub(r"//.*", "", body)
    members, value = [], 0
    for part in body.split(","):
        part = part.strip()
        if not part:
            continue
        m = re.fullmatch(r"(\w+)\s*(?:=\s*([0-9A-Fa-fx+ ]+))?", part)
        if not m:
            raise SystemExit(f"cannot parse {name} member: {part!r}")
        if m.group(2):
            value = sum(int(x, 0) for x in m.group(2).split("+"))
        members.append((m.group(1), value))
        value += 1
    return members


out = ["/* Generated by tools/gen_enums.py from the Cas' tracker enums. Do not edit. */",
       "#ifndef SMZ3_ENUMS_H", "#define SMZ3_ENUMS_H", ""]
for name, prefix in (("ItemType", "ITEM"), ("RewardType", "REWARD"), ("BossType", "BOSS"), ("LocationId", "LOC")):
    files = list(enums.glob(f"{name}.cs"))
    if not files:
        files = [p for p in root.glob(f"vendor/SMZ3Randomizer/src/**/{name}.cs")]
    members = parse(files[0], name)
    out.append(f"enum {{")
    for n, v in members:
        out.append(f"    {prefix}_{n} = {v},")
    out.append(f"    {prefix}_COUNT_ = {max(v for _, v in members) + 1}")
    out.append("};")
    out.append("")
out.append("#endif")
(root / "core/gen/smz3_enums.h").write_text("\n".join(out) + "\n")
print("ok")
