#!/usr/bin/env python3
"""Packs the *.ips patches of a folder into a C table (name, data, length) so the PC binary needs no data files."""
import os, sys
src, dst = sys.argv[1], sys.argv[2]
names = sorted(n for n in os.listdir(src) if n.endswith(".ips"))
out = ["/* Generated by tools/gen_ips_c.py. Do not edit. */", "#include <stddef.h>", "#include \"pc_ips.h\""]
for i, n in enumerate(names):
    data = open(os.path.join(src, n), "rb").read()
    out.append(f"static const unsigned char ips_{i}[] = {{" + ",".join(str(b) for b in data) + "};")
out.append("const PcIps PC_IPS[] = {")
for i, n in enumerate(names):
    out.append(f'    {{"{n}", ips_{i}, sizeof ips_{i}}},')
out.append("    {NULL, NULL, 0}\n};")
open(dst, "w").write("\n".join(out) + "\n")
