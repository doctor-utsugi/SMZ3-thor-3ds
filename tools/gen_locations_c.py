#!/usr/bin/env python3
"""Generates core/smz3_locations.c from data/locations.json."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
locs = json.loads((root / "data/locations.json").read_text())


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ['/* Generated by tools/gen_locations_c.py from data/locations.json. Do not edit. */',
         '#include "smz3_state.h"', '',
         'const smz3_location smz3_locations[] = {']
for l in locs:
    game = "SMZ3_GAME_ZELDA" if l["game"] == "zelda" else "SMZ3_GAME_METROID"
    misc = 1 if l["mem_type"] == "ZeldaMisc" else 0
    lines.append(f'    {{{q(l["id"])}, {q(l["name"])}, {q(l["region_name"])}, {game}, {misc}, 0x{l["mem_addr"]:X}, 0x{l["mem_flag"]:X}}},')
lines += ['};', '', f'const unsigned smz3_location_count = {len(locs)};', '']
(root / "core/smz3_locations.c").write_text("\n".join(lines))
print(len(locs), "locations written")
