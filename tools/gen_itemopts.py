#!/usr/bin/env python3
"""Generates core/gen/smz3_itemopts_data.h from the tracker's ItemSettingOptions.yml: the start-with / early item choices."""
import os, re, sys, yaml
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = root + "/vendor/SMZ3Randomizer/src/TrackerCouncil.Smz3.Data/Options/ItemSettingOptions.yml"
enums = open(root + "/core/gen/smz3_enums.h").read()
known = set(re.findall(r"\bITEM_(\w+)\s*=", enums))
groups = yaml.safe_load(open(src))
out = ["/* Generated by tools/gen_itemopts.py from ItemSettingOptions.yml. Do not edit. */",
       "#ifndef SMZ3_ITEMOPTS_DATA_H", "#define SMZ3_ITEMOPTS_DATA_H", "",
       "typedef struct { const char *name; int is_metroid, first, count; } SmzItemOptGroup;",
       "/* has_mem: the option has MemoryValues (a start-with option); matches are the MatchingItemTypes */",
       "typedef struct { const char *display; int has_mem, mem_first, mem_count, match_first, match_count; } SmzItemOpt;",
       "typedef struct { int key, value; } SmzItemOptMem;", ""]
gs, os_, mem, match = [], [], [], []
for g in groups:
    first = len(os_)
    for o in g["Options"]:
        mv = o.get("MemoryValues")
        mt = o.get("MatchingItemTypes") or []
        for t in mt:
            if t not in known: sys.exit("unknown item type " + t)
        os_.append('    { "%s", %d, %d, %d, %d, %d },' % (o["Display"].replace('"', '\\"'), 1 if mv is not None else 0,
                   len(mem), len(mv or {}), len(match), len(mt)))
        for k, v in (mv or {}).items(): mem.append("{ %d, %d }" % (k, v))
        for t in mt: match.append("ITEM_" + t)
    gs.append('    { "%s", %d, %d, %d },' % (g["Item"], 1 if g["IsMetroid"] else 0, first, len(g["Options"])))
out += ["#define SMZ_ITEMOPT_GROUPS %d" % len(gs), "static const SmzItemOptGroup SMZ_ITEMOPT_GROUP[] = {"] + gs + ["};", "",
        "static const SmzItemOpt SMZ_ITEMOPT[] = {"] + os_ + ["};", "",
        "static const SmzItemOptMem SMZ_ITEMOPT_MEM[] = {", "    " + ", ".join(mem), "};", "",
        "static const int SMZ_ITEMOPT_MATCH[] = {", "    " + ", ".join(match), "};", "", "#endif", ""]
open(root + "/core/gen/smz3_itemopts_data.h", "w").write("\n".join(out))

# the Items tab of the Create run menu: one enum row per option group
def short(d):
    return d.replace("Start with ", "Have ").replace("Have 10 bombs, 30 arrows, and full magic", "Have bombs, arrows, magic")
ui = ["/* Generated by tools/gen_itemopts.py. Do not edit. One UiOptDef per start-with / early item group. */"]
for gi, g in enumerate(groups):
    names = ", ".join('"%s"' % short(o["Display"]).replace('"', '\\"') for o in g["Options"])
    ui.append("static const char *const N_ITEM_%d[] = {%s};" % (gi, names))
ui.append("#define ITEM_OPT_DEFS \\")
for gi, g in enumerate(groups):
    ui.append('    {"opt:%s", "%s", "Have it from the start, or find it early (spheres 1 to 3).", OPT_ENUM, LEVEL_ITEMS, 0, %d, 0, N_ITEM_%d},%s' % (
        g["Item"], g["Item"], len(g["Options"]) - 1, gi, " \\" if gi < len(groups) - 1 else ""))
open(root + "/core/ui/smz3_ui_items.h", "w").write("\n".join(ui) + "\n")
print(len(gs), "groups", len(os_), "options")
