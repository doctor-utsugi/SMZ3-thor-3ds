#!/usr/bin/env python3
"""Generates core/gen/smz3_hints_data.h: the world independent hint pool, tile keys and location names.
Input: build/hintdata.json (gen-cli hintdata)."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(root + "/build/hintdata.json"))

def cstr(s):
    out = ['"']
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"' or c == "\\": out.append("\\" + c)
        elif 32 <= b < 127: out.append(c)
        else: out.append("\\%03o" % b)
    out.append('"')
    return "".join(out)

locs = {l["id"]: l for l in d["locations"]}
rooms = {r["name"]: r["names"] for r in d["rooms"]}
o = ["/* Generated by tools/gen_hints.py. Do not edit. */", "#ifndef SMZ3_HINTS_DATA_H", "#define SMZ3_HINTS_DATA_H", ""]
o.append("static const char *const SMZ_HINT_TILES[] = { %s };" % ", ".join(cstr(k) for k in d["tiles"]))
o.append("#define SMZ_HINT_TILE_COUNT %d" % len(d["tiles"]))
o.append("")

def arr(name, ids):
    o.append("static const uint16_t %s[] = { %s };" % (name, ", ".join(str(i) for i in ids)))

o.append("typedef struct { int region, nloc; const uint16_t *locs; } SmzHintDungeon;")
dungeons = [(e, "RR") for e in d["rewardRegions"]] + [(e, "FD") for e in d["fixedDungeons"]]
for i, (e, p) in enumerate(dungeons): arr("HD_%d" % i, e["locations"])
rr = len(d["rewardRegions"])
o.append("static const SmzHintDungeon SMZ_HINT_DUNGEONS[] = {")
for i, (e, p) in enumerate(dungeons):
    o.append("    { %d, %d, HD_%d }," % (e["region"], len(e["locations"]), i))
o.append("};")
o.append("#define SMZ_HINT_REWARD_DUNGEONS %d" % rr)
o.append("#define SMZ_HINT_DUNGEON_COUNT %d" % len(dungeons))
o.append("")

regions_by_loc = {l["id"]: l["region"] for l in d["locations"]}
o.append("enum { HT_Location, HT_LocationGroup, HT_Room, HT_Region, HT_Dungeon, HT_Requirement };")
o.append("typedef struct { int type, region, nloc; const uint16_t *locs; const char *key; SmzStrList names; } SmzHintDef;")
for i, e in enumerate(d["locationHints"]):
    arr("HL_%d" % i, e["locations"])
    if e["type"] == "Room":
        ns = rooms[e["key"]]
        o.append("static const char *const HLN_%d[] = { %s };" % (i, ", ".join(cstr(n) for n in ns)))
o.append("static const SmzHintDef SMZ_HINT_LOCATIONS[] = {")
for i, e in enumerate(d["locationHints"]):
    reg = regions_by_loc[e["locations"][0]]
    names = "{ %d, HLN_%d }" % (len(rooms[e["key"]]), i) if e["type"] == "Room" else "{ 0, 0 }"
    o.append("    { HT_%s, %d, %d, HL_%d, %s, %s }," % (e["type"], reg, len(e["locations"]), i, cstr(e["key"]), names))
o.append("};")
o.append("#define SMZ_HINT_LOCATION_COUNT %d" % len(d["locationHints"]))
o.append("")
# medallions: the region is the dungeon whose medallion is asked for
region_idx = {}
for e in d["rewardRegions"]: region_idx[e["key"]] = e["region"]
o.append("static const int SMZ_HINT_MEDALLION_REGIONS[] = { %s };" % ", ".join(str(region_idx[e["key"]]) for e in d["medallions"]))
o.append("#define SMZ_HINT_MEDALLION_COUNT %d" % len(d["medallions"]))
o.append("")
# location names ("<region> - <location>" uses the region names from the text data)
for l in d["locations"]:
    o.append("static const char *const LN_%d[] = { %s };" % (l["id"], ", ".join(cstr(n) for n in l["names"]) or "0"))
o.append("static const SmzStrList SMZ_LOC_NAMES[512] = {")
for l in d["locations"]:
    o.append("    [%d] = { %d, LN_%d }," % (l["id"], len(l["names"]), l["id"]))
o.append("};")
o.append("")
o.append("#endif")
open(root + "/core/gen/smz3_hints_data.h", "w").write("\n".join(o) + "\n")
print("ok", len(d["locations"]), "locations")
