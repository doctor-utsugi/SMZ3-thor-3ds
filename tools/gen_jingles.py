#!/usr/bin/env python3
"""Generates core/gen/smz3_jingles_data.h: the patches of every fixed Etecoons jingle, dumped from the C# oracle.
Usage: dotnet gen-cli placementbatch build/jingle_cases.jsonl build/jingle_cs.txt (one case per jingle, in order), then this script."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = json.load(open(root + "/build/jingle_names.json"))
blocks = open(root + "/build/jingle_cs.txt").read().split("case\n")[1:]
blocks = [b for b in blocks if b]
assert len(blocks) == len(names), (len(blocks), len(names))
out = ["/* Generated by tools/gen_jingles.py from the C# EtecoonsJinglePatch. Do not edit. */", "#ifndef SMZ3_JINGLES_DATA_H", "#define SMZ3_JINGLES_DATA_H", "",
       "typedef struct { int offset; int len; const unsigned char *data; } SmzJinglePatch;", ""]
tables = []
for i, (n, blk) in enumerate(zip(names, blocks)):
    rows = []
    for l in blk.split("\n"):
        if l.startswith("P\tEtecoonsJinglePatch\t"):
            _, _, off, hexs = l.split("\t")
            rows.append((int(off, 16), bytes.fromhex(hexs)))
    for j, (off, d) in enumerate(rows):
        out.append("static const unsigned char JG_%d_%d[] = {%s};" % (i, j, ",".join("0x%02X" % b for b in d)))
    out.append("static const SmzJinglePatch JG_%d[] = {%s};" % (i, ", ".join("{0x%X, %d, JG_%d_%d}" % (off, len(d), i, j) for j, (off, d) in enumerate(rows))))
    tables.append("{\"%s\", %d, JG_%d}" % (n, len(rows), i))
out += ["", "#define SMZ_JINGLE_COUNT %d" % len(names), "static const struct { const char *name; int n; const SmzJinglePatch *patches; } SMZ_JINGLES[] = {", "    " + ",\n    ".join(tables), "};", "", "#endif", ""]
open(root + "/core/gen/smz3_jingles_data.h", "w").write("\n".join(out))
print(len(names), "jingles")
