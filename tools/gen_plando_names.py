#!/usr/bin/env python3
"""Generates core/gen/smz3_plando_names.h: the location names a plando config uses (Location.ToString() of the C# oracle).
Usage: dotnet gen-cli placementbatch build/one.jsonl build/one_cs.txt (any one case), then this script."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for l in open(root + "/build/one_cs.txt").read().split("\n"):
    if l.startswith("N\t"):
        _, i, n = l.split("\t")
        rows.append((int(i), n))
out = ["/* Generated by tools/gen_plando_names.py. Do not edit. */", "#ifndef SMZ3_PLANDO_NAMES_H", "#define SMZ3_PLANDO_NAMES_H", "",
       "typedef struct { int id; const char *name; } SmzLocName;", "static const SmzLocName SMZ_LOC_NAMES[] = {"]
out += ['    { %d, "%s" },' % (i, n.replace('"', '\\"')) for i, n in rows]
out += ["};", "#define SMZ_LOC_NAME_COUNT %d" % len(rows), "", "#endif", ""]
open(root + "/core/gen/smz3_plando_names.h", "w").write("\n".join(out))
print(len(rows), "locations")
