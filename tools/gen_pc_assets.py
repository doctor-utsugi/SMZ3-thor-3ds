#!/usr/bin/env python3
"""Packs the map assets of the app (map image, room table, region boxes, location markers) into a C file for the PC binary."""
import json, os, sys
src, dst = sys.argv[1], sys.argv[2]
rooms = json.load(open(os.path.join(src, "sm_rooms.json")))
regions = json.load(open(os.path.join(src, "z3_regions.json")))
markers = json.load(open(os.path.join(src, "map_markers.json")))
png = open(os.path.join(src, "map.png"), "rb").read()
out = ["/* Generated by tools/gen_pc_assets.py. Do not edit. */", "#include \"smz3_discovery.h\"", "#include \"pc_assets.h\""]
out.append("static const SmzSmRoom ROOMS[] = {" + ",".join("{%d,%d,%d,%d,%d,%d}" % tuple(r) for r in rooms) + "};")
out.append("static const SmzZRegion REGIONS[] = {" + ",".join('{"%s",{%s}}' % (k.replace('"', '\\"'), ",".join("%g.0f" % v if float(v).is_integer() else "%gf" % v for v in b)) for k, b in regions.items()) + "};")
out.append("static const SmzMarker MARKERS[] = {" + ",".join("{%d,%d,%d}" % tuple(m) for m in markers) + "};")
out.append("const SmzMapData PC_MAP_DATA = {ROOMS, %d, REGIONS, %d, MARKERS, %d};" % (len(rooms), len(regions), len(markers)))
out.append("const unsigned char PC_MAP_PNG[] = {" + ",".join(str(b) for b in png) + "};")
out.append("const unsigned PC_MAP_PNG_LEN = %d;" % len(png))
icons = sorted(os.listdir(os.path.join(src, "items")))
# the boss tokens of the run list, named "rewards/<file>" beside the item icons (paths are relative to items/)
icons += ["../rewards/" + n for n in sorted(os.listdir(os.path.join(src, "rewards")))]
# the country flags (assets/flags, made by tools/gen_flags.py), named "flags/<CODE>.png"
flags = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "flags")
icons += [os.path.join(flags, n) for n in sorted(os.listdir(flags))]
for i, n in enumerate(icons):
    out.append("static const unsigned char icon_%d[] = {" % i + ",".join(str(b) for b in open(os.path.join(src, "items", n), "rb").read()) + "};")
out.append("const PcIcon PC_ITEM_ICONS[] = {")
for i, n in enumerate(icons):
    out.append('    {"%s", icon_%d, sizeof icon_%d},' % ((n.replace("../", "") if not os.path.isabs(n) else "flags/" + os.path.basename(n)).replace('"', '\\"'), i, i))
out.append("    {NULL, NULL, 0}\n};")
open(dst, "w").write("\n".join(out) + "\n")
